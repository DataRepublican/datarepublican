/* Turn *.embed.js logo blobs into real image files.
 *
 * Those files assign `window.LOGOS = {key: {bg, tile, uri}}` where `uri` is a
 * base64 data URI, and dsa-explorer/index.html loads all four as blocking
 * <script> tags before anything renders — 23.4 MB of PNG parsed as JavaScript,
 * on the critical path, uncacheable separately from each other, and re-parsed
 * on every visit.
 *
 * This writes each image to logos/img/<source>/<key>.<ext> and emits
 * logos/index.js carrying the same two globals with `uri` pointing at a path
 * instead. Cytoscape's background-image takes a URL exactly as it takes a data
 * URI, so nothing downstream changes.
 *
 * Run from the repo root:  node scripts/extract-logo-blobs.mjs
 * It is idempotent and safe to re-run when the pipeline drops new blobs in.
 */
import { readFileSync, writeFileSync, mkdirSync, rmSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = 'dsa-explorer/logos';
const OUT = join(ROOT, 'img');

// Load order matters: index.html merges LOGOS, then AVATARS, EMBLEMS and
// AFGJ_LOGOS override it — except `hatuey`, which keeps its branded LOGOS entry.
const SOURCES = [
  ['logos', 'logos.embed.js', 'LOGOS'],
  ['avatars', 'avatars.embed.js', 'AVATARS'],
  ['emblems', 'emblems.embed.js', 'EMBLEMS'],
  ['afgj', 'afgj_logos.embed.js', 'AFGJ_LOGOS'],
];

global.window = {};
for (const [, file] of SOURCES) {
  // eslint-disable-next-line no-eval
  (0, eval)(readFileSync(join(ROOT, file), 'utf8'));
}

rmSync(OUT, { recursive: true, force: true });

const EXT = { 'image/png': 'png', 'image/jpeg': 'jpg', 'image/webp': 'webp', 'image/svg+xml': 'svg', 'image/gif': 'gif' };
const safe = (k) => String(k).replace(/[^A-Za-z0-9._-]/g, '_');

let written = 0, bytes = 0;
const maps = {};

for (const [dir, , globalName] of SOURCES) {
  const src = global.window[globalName] || {};
  mkdirSync(join(OUT, dir), { recursive: true });
  const seen = new Map();
  const out = {};

  for (const [key, entry] of Object.entries(src)) {
    const uri = entry && entry.uri;
    if (typeof uri !== 'string' || !uri.startsWith('data:')) {
      out[key] = entry;
      continue;
    }
    const m = uri.match(/^data:([^;,]+);base64,(.*)$/s);
    if (!m) { out[key] = entry; continue; }

    const ext = EXT[m[1]] || 'bin';
    let name = `${safe(key)}.${ext}`;
    // Sanitising can collide (two keys differing only in punctuation).
    if (seen.has(name) && seen.get(name) !== key) {
      let n = 2;
      while (seen.has(`${safe(key)}-${n}.${ext}`)) n += 1;
      name = `${safe(key)}-${n}.${ext}`;
    }
    seen.set(name, key);

    const buf = Buffer.from(m[2], 'base64');
    writeFileSync(join(OUT, dir, name), buf);
    written += 1; bytes += buf.length;

    out[key] = { ...entry, uri: `logos/img/${dir}/${name}` };
  }
  maps[globalName] = out;
}

// Reproduce index.html's merge exactly, so the page can drop its inline block.
const hatuey = maps.LOGOS.hatuey;
const merged = { ...maps.LOGOS, ...maps.AVATARS, ...maps.EMBLEMS, ...maps.AFGJ_LOGOS };
if (hatuey) merged.hatuey = hatuey;   // canonical Hatuey keeps its branded logo

const banner = `/* GENERATED by scripts/extract-logo-blobs.mjs — do not edit by hand.
 *
 * Replaces logos.embed.js, avatars.embed.js, emblems.embed.js and
 * afgj_logos.embed.js, which together were 23.4 MB of base64 loaded as blocking
 * scripts. The images live in logos/img/ and load lazily as the graph draws
 * them; \`uri\` is now a path.
 *
 * window.LOGOS is already merged in the order index.html used to merge it:
 * logos, then avatars, emblems and afgj override, except hatuey.
 * window.AVATARS is kept separate because person nodes prefer an avatar over an
 * emblem of the same id.
 */\n`;

writeFileSync(
  join(ROOT, 'index.js'),
  banner +
    `window.AVATARS = ${JSON.stringify(maps.AVATARS)};\n` +
    `window.LOGOS = ${JSON.stringify(merged)};\n`
);

console.log(`wrote ${written} images, ${(bytes / 1048576).toFixed(1)} MB`);
console.log(`logos/index.js: ${(readFileSync(join(ROOT, 'index.js')).length / 1024).toFixed(0)} KB`);
console.log(`LOGOS entries: ${Object.keys(merged).length}, AVATARS: ${Object.keys(maps.AVATARS).length}`);

/* ---------------------------------------------------------------------------
 * noblogs/graph — window.NODE_LOGOS, 294 entries, 12.58 MB on the wire, which
 * made it the largest single asset on the site once the dsa blobs were gone.
 *
 * Paths here are relative to noblogs/graph/, and graph.js is loaded from two
 * different depths — /noblogs/graph/ standalone and /noblogs/ for the Graph
 * tab — so the module prefixes them with its `assetBase` option rather than
 * the path being absolute.
 */
{
  const NB = 'noblogs/graph';
  const NBOUT = join(NB, 'img');
  global.window = {};
  // eslint-disable-next-line no-eval
  (0, eval)(readFileSync(join(NB, 'logos.embed.js'), 'utf8'));

  rmSync(NBOUT, { recursive: true, force: true });
  mkdirSync(NBOUT, { recursive: true });

  const src = global.window.NODE_LOGOS || {};
  const out = {};
  const seen = new Map();
  let n = 0, nbytes = 0;

  for (const [key, entry] of Object.entries(src)) {
    const uri = entry && entry.uri;
    const m = typeof uri === 'string' && uri.match(/^data:([^;,]+);base64,(.*)$/s);
    if (!m) { out[key] = entry; continue; }

    const ext = EXT[m[1]] || 'bin';
    let name = `${safe(key)}.${ext}`;
    if (seen.has(name) && seen.get(name) !== key) {
      let i = 2;
      while (seen.has(`${safe(key)}-${i}.${ext}`)) i += 1;
      name = `${safe(key)}-${i}.${ext}`;
    }
    seen.set(name, key);

    const buf = Buffer.from(m[2], 'base64');
    writeFileSync(join(NBOUT, name), buf);
    n += 1; nbytes += buf.length;
    out[key] = { ...entry, uri: `img/${name}` };
  }

  writeFileSync(join(NB, 'logos.index.js'),
    `/* GENERATED by scripts/extract-logo-blobs.mjs — do not edit by hand.
 * Replaces logos.embed.js (12.58 MB on the wire). Images live in
 * noblogs/graph/img/ and \`uri\` is a path relative to noblogs/graph/.
 */\n` + `window.NODE_LOGOS = ${JSON.stringify(out)};\n`);

  console.log(`noblogs/graph: wrote ${n} images, ${(nbytes / 1048576).toFixed(1)} MB`);
  console.log(`  logos.index.js: ${(readFileSync(join(NB, 'logos.index.js')).length / 1024).toFixed(0)} KB`);
}
